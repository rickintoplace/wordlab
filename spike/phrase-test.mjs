import { readFileSync } from 'node:fs';
const dir = process.argv[2];
const f32 = f => { const b = readFileSync(f); return new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
let resolveNext;
globalThis.self = { postMessage: m => resolveNext?.(m) };
globalThis.fetch = async url => ({ text: async () => readFileSync(new URL(`../public${url.split('?')[0]}`, import.meta.url), 'utf8') });
await import('../public/slinky/worker.js');
const send = (m, t) => new Promise(r => { resolveNext = x => { if (x.type === t || x.type === 'error') r(x); }; self.onmessage({ data: m }); });
const raw = JSON.parse(readFileSync(`${dir}/words.json`)).words;
const ready = await send({ type: 'build', key: 'x', lang: 'de', words: raw, post: f32(`${dir}/post.bin`), ...JSON.parse(readFileSync(`${dir}/post.json`)), voice16: f32(`${dir}/a16.f32`), voice48: f32(`${dir}/a48.f32`), music48: null }, 'ready');
const si = [0, 1, 2, 3, 4, 5, 6];
const ws = ready.words;
console.log('Original:', si.map(i => ws[i].w).join(' '), `${ws[si[0]].s.toFixed(2)}–${ws[si.at(-1)].e.toFixed(2)} (${(ws[si.at(-1)].e - ws[si[0]].s).toFixed(2)} s)`);
const p = await send({ type: 'phrase', id: 1, si }, 'phrase');
console.log(p.message ?? '', 'Satz:', p.words.map(w => `${w.w}[${w.quality}]`).join(' '), (p.audio.length / 48000).toFixed(2), 's; Wörter', p.words[0].start.toFixed(2), '–', p.words.at(-1).end.toFixed(2), 'Stücke', p.pieces.length);
const v = await send({ type: 'variants', id: 2, text: p.text, force: p.force, wi: 4 }, 'variants');
console.log('Wort 4:', v.message ?? '', v.options.map(o => `${o.info?.kind}:${o.info?.word ?? o.info?.from?.join('+')}${o.current ? '*' : ''} ${o.words[4].quality}`).join(' | '));
const sv = await send({ type: 'sylVariants', id: 3, text: p.text, force: p.force, wi: 5, si: 1 }, 'variants');
console.log('Silbe:', sv.message ?? '', sv.options.map(o => `${o.label}${o.current ? '*' : ''} → ${o.words.map(w => w.quality[0]).join('')}`).join(' | '));
